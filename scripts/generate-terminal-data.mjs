// Generates public/terminal/terminal-data.js and api/cli_data.json from the
// site's real data, so
// the web terminal's rich commands (projects, work, blog, wins, contact)
// can't drift from the SPA the way the hand-ported snapshot in
// terminal-engine.js / api/cli.py does.
//
// Loads src/data/*.js, the EXP array in Experience.jsx and the corkboard's
// win list through Vite's ssrLoadModule (same trick as prerender.mjs), so JSX
// modules load in plain Node with no build step. Output is a plain script
// that sets window.TERMINAL_DATA; the terminal stays zero-build.
//
// Usage: npm run generate:terminal
import { createServer } from 'vite'
import { writeFile } from 'fs/promises'
import { fileURLToPath } from 'url'
import { dirname, join } from 'path'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = join(__dirname, '..')

const vite = await createServer({ root, server: { middlewareMode: true }, appType: 'custom', logLevel: 'warn' })
try {
  const { PROJECTS } = await vite.ssrLoadModule('/src/data/projects.js')
  const { POSTS } = await vite.ssrLoadModule('/src/data/blog.js')
  const { EXP } = await vite.ssrLoadModule('/src/components/Experience.jsx')
  const { ITEMS } = await vite.ssrLoadModule('/src/three/room/corkData.js')
  const { BIRTH_ISO } = await vite.ssrLoadModule('/src/utils/meta.js')
  const { SIDE_PROJECTS } = await vite.ssrLoadModule('/src/data/sideProjects.js')

  const firstPara = p => (p.content || []).find(b => b.type === 'paragraph')?.text ?? ''
  const data = {
    generated: new Date().toISOString().slice(0, 10),
    // never a literal age: the terminal computes it from this at runtime
    birth: BIRTH_ISO,
    projects: PROJECTS.map(p => ({
      slug: p.slug, name: p.name, tagline: p.tagline, period: p.period, stat: p.stat,
      tags: p.tags || [], desc: p.desc, problem: p.problem, solution: p.solution,
      how: (p.how || []).map(h => ({ label: h.label, text: h.text })),
      impact: (p.impact || []).map(m => ({ val: String(m.val), label: m.label })),
      github: p.github || null, live: p.live || null,
    })),
    work: EXP.map(e => ({
      org: e.org, role: e.primaryRole, type: e.type, period: e.period, live: !!e.live,
      desc: e.desc, skills: e.skills || [], extra: e.extra || [], cta: e.cta || null,
    })),
    posts: POSTS.map(p => ({
      slug: p.slug, title: p.title, subtitle: p.subtitle, category: p.category,
      date: p.date, readTime: p.readTime, external: p.externalUrl || null, lede: firstPara(p),
      quote: (p.content || []).find(b => b.type === 'pullquote')?.text ?? null,
    })),
    wins: ITEMS.filter(i => i.id.startsWith('win-')).map(i => ({
      title: i.panel.title, sub: i.panel.sub || '', text: i.panel.text, project: i.panel.project || null,
    })),
    side: SIDE_PROJECTS.map(s => ({
      name: s.name, line: s.line, desc: s.desc || s.line, status: s.status, github: s.href || null, live: s.live || null,
    })),
    // one copy for both terminals (web renders `about` with links of its own)
    about: {
      lead: "I don't wait to be qualified. I ship things, see what breaks, and figure it out from there.",
      body: [
        'Leading Bits&Bytes Kolkata, consulting at 4MQ.org, and building open-source tools that solve real gaps, not demo projects.',
        'Work spans hardware (LiFi mesh networks, Arduino reaction simulators), AI research (planning failures, published on Zenodo), and product: Buy4Chai for India\'s Stripe exclusion problem, SarkarSathi for civic accountability.',
        'The thread: constraint thinking. Building the right thing with what\'s actually available.',
      ],
    },
    skills: ['Python', 'C++', 'JavaScript', 'Arduino', 'IoT', 'Flask', 'Linux (Pop!_OS)', 'Vercel', 'Razorpay / UPI', 'AI / planning systems', 'Hardware', 'Product design', 'Systems thinking', 'Constraint thinking'],
  }

  const out = `// GENERATED by scripts/generate-terminal-data.mjs — do not edit by hand.\n// Run \`npm run generate:terminal\` after changing src/data, Experience.jsx or corkData.js.\nwindow.TERMINAL_DATA = ${JSON.stringify(data, null, 1)};\n`
  await writeFile(join(root, 'public/terminal/terminal-data.js'), out)
  // the curl backend (api/cli.py) reads the same data — bundled next to it
  await writeFile(join(root, 'api/cli_data.json'), JSON.stringify(data, null, 1) + '\n')
  console.log(`terminal-data.js: ${data.projects.length} projects, ${data.side.length} side projects, ${data.work.length} roles, ${data.posts.length} posts, ${data.wins.length} wins`)
} finally {
  await vite.close()
}
